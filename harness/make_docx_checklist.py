#!/usr/bin/env python3
"""List every change to be carried into the Word file, generated from the diff.

The revised manuscript is assembled by hand in Word from the template, so the only
thing standing between the markdown and the .docx is a person reading a list. This
generates that list from the two files rather than from memory: the submitted
snapshot against the current manuscript, one entry per changed passage, with the new
text in full so it can be pasted.

Usage: python3 harness/make_docx_checklist.py
"""
import difflib, pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
PAPER = ROOT / 'BPPB-special-issue-paper'
OLD = PAPER / '20260911_1st_submission'
OUT = PAPER / '20261008_1st_revision' / 'docx-changes.md'

# which reviewer comment each section's changes answer, for the right-hand column
WHY = {
    'Tasks, guideline document, manuscripts, and ground truth': 'R1-1, R1-3, R2-3',
    'Prompts, inference parameters, and scoring': 'R2-2, R2-3',
    'Workstation and inference stack': 'R2-4',
    'Measurement of inference speed and memory usage': 'R2-4',
    'Model rank within each task (T1–T8)': 'R1-1',
    'Effects of prompt structure, quantization, and model generation on score (T1 and T8)':
        'R2-3',
    'Discussion': 'R2-1, R2-3',
}


def sections(lines):
    out, cur = [], '(front matter)'
    for l in lines:
        if l.startswith(('## ', '### ')):
            cur = l.lstrip('# ')
        out.append(cur)
    return out


def main():
    a = (OLD / 'manuscript.md').read_text().split('\n')
    b = (PAPER / 'manuscript.md').read_text().split('\n')
    sec = sections(b)
    parts = ["""# Changes to carry into the Word file

Generated by `harness/make_docx_checklist.py` from the submitted snapshot against the
current manuscript. Regenerate it after any further edit; do not tick a box from memory.

The new text below is the text to paste. Where a passage replaces an earlier one, the
earlier text is given so the right paragraph can be found in the Word file.

""", '## Text\n']
    n = 0
    for tag, i1, i2, j1, j2 in difflib.SequenceMatcher(None, a, b,
                                                       autojunk=False).get_opcodes():
        if tag == 'equal':
            continue
        n += 1
        where = sec[j1] if j1 < len(sec) else sec[-1]
        old = ' '.join(x for x in a[i1:i2] if x.strip())
        new = '\n'.join(b[j1:j2]).strip()
        parts.append(f"### {n}. {where}  ·  {WHY.get(where, '')}\n")
        if old.strip():
            parts.append(f"Replaces:\n\n> {old}\n")
        else:
            parts.append(f"New paragraph, inserted at this point in the section.\n")
        parts.append(f"Paste:\n\n```\n{new}\n```\n")

    figs = sorted((PAPER / 'figures').glob('figure*.png')) + \
        [PAPER / 'figures' / 'graphical_abstract.png']
    changed = [f.name for f in figs
               if not (OLD / 'figures' / f.name).exists()
               or f.read_bytes() != (OLD / 'figures' / f.name).read_bytes()]
    parts.append('\n## Figures\n')
    parts.append('Replace these in the Word file; the others are unchanged.\n')
    for f in figs:
        mark = 'REPLACE' if f.name in changed else 'unchanged'
        parts.append(f'- [{"x" if f.name in changed else " "}] `{f.name}` — {mark}')
    parts.append(f'\n{len(changed)} of {len(figs)} figures changed.\n')
    OUT.write_text('\n'.join(parts))
    print(f'wrote {OUT.relative_to(ROOT)}: {n} text changes, '
          f'{len(changed)} figures to replace')


if __name__ == '__main__':
    main()
